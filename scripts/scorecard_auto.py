def main():
    d = json.load(open(P("prereg", "scorecard_clauses.json")))
    rows, dis = [], []
    for j in d["jobs"]:
        for c in j["clauses"]:
            a, why = auto(c)
            rows.append(dict(id=c["id"], hand=c["status"], auto=a, why=why))
            if a is not None and a != c["status"]:
                dis.append(dict(id=c["id"], threshold=c.get("threshold"), measured=c.get("measured"), ci=c.get("ci"), hand=c["status"], auto=a, note=c.get("note", "")))
    n_auto = sum(r["auto"] is not None for r in rows)
    agree = sum(r["auto"] == r["hand"] for r in rows if r["auto"] is not None)
    why = Counter(r["why"] for r in rows if r["auto"] == "held (point)")
    p99 = P("prereg", "scorecard_099.json")
    j99 = json.load(open(p99))["clauses"] if os.path.exists(p99) else []
    out = dict(n=len(rows), n_auto=n_auto, agree=agree, disagreements=dis, point_reasons=dict(why),
               job099=dict(n=len(j99), status=dict(Counter(c["status"] for c in j99)), why=dict(Counter(c["why"] for c in j99 if c["why"]))))
    json.dump(out, open(P("prereg", "scorecard_auto.json"), "w"), indent=1)
    det = sum(1 for x in dis if x["hand"] == "held" and x["auto"] == "held (point)" and x["ci"] is None)
    out["deterministic_held_outright"] = det
    json.dump(out, open(P("prereg", "scorecard_auto.json"), "w"), indent=1)
    M = dict(scaN=str(len(rows)), scaAuto=str(n_auto), scaAgree=str(agree), scaDisagree=str(len(dis)), scaDet=str(det),
             scaOther=str(len(dis) - det),
             scaNoInterval=str(why.get("no interval", 0)), scaCrosses=str(why.get("interval crosses", 0)))
    st = Counter(c["status"] for c in j99)
    M.update(scbN=str(len(j99)), scbHeld=str(st.get("held", 0)), scbPoint=str(st.get("held (point)", 0)), scbFailed=str(st.get("failed", 0)),
             scbUntested=str(st.get("untested", 0)))
    with open(P("paper", "wsg_scauto.tex"), "w") as f:
        f.write("% generated by scripts/scorecard_auto.py\n")
        for k in sorted(M):
            f.write(f"\\newcommand{{\\{k}}}{{{M[k]}}}\n")
    if j99:
        write_099(j99, P("paper", "tab_scorecard_099.tex"))
    p101 = P("prereg", "scorecard_101.json")
