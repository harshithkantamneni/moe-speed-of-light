"""Machine re-scoring of the hand-encoded scorecard (prereg/scorecard_clauses.json) and of job 099
(prereg/scorecard_099.json, already machine-scored): every clause whose measured value is a number and whose threshold
parses (> x, >= x, < x, <= x, a to b, a-b, [a, b], within +-x, -x to +x) is scored again from its measured value and
interval under the rule in the file's meta.ci_rule, with 'held (point)' split into 'no interval' and 'interval
crosses'. Writes prereg/scorecard_auto.json (agreement with the hand scores, every disagreement) and
paper/wsg_scauto.tex.

    python scripts/scorecard_auto.py
"""
import json
import os
import re
from collections import Counter

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
P = lambda *a: os.path.join(ROOT, *a)  # noqa: E731
NUM = r"([+-]?\d+(?:\.\d+)?)"


def predicate(thr):
    t = thr.strip().replace("−", "-").replace("%", "").replace("x", "").strip()
    t = re.sub(r"\s+at every budget$", "", t)
    m = re.fullmatch(r"(>=|<=|>|<)\s*" + NUM, t)
    if m:
        op, v = m.group(1), float(m.group(2))
        return {">": lambda x: x > v, ">=": lambda x: x >= v, "<": lambda x: x < v, "<=": lambda x: x <= v}[op]
    m = re.fullmatch(r"within\s*\+-\s*" + NUM, t)
    if m:
        v = abs(float(m.group(1)))
        return lambda x: -v <= x <= v
    m = re.fullmatch(r"\[\s*" + NUM + r"\s*,\s*" + NUM + r"\s*\]", t) or re.fullmatch(NUM + r"\s*(?:to|-)\s*" + NUM, t)
    if m:
        lo, hi = float(m.group(1)), float(m.group(2))
        if lo > hi:
            lo, hi = hi, lo
        return lambda x: lo <= x <= hi
    return None


def auto(c):
    meas, thr, ci = c.get("measured"), c.get("threshold"), c.get("ci")
    if c.get("status") in ("void", "untested") or not isinstance(meas, (int, float)) or isinstance(meas, bool) or not isinstance(thr, str):
        return None, ""
    ok = predicate(thr)
    if ok is None:
        return None, ""
    if not ok(meas):
        return "failed", ""
    if not (isinstance(ci, list) and len(ci) == 2 and all(isinstance(v, (int, float)) for v in ci)):
        return "held (point)", "no interval"
    if ok(ci[0]) and ok(ci[1]):
        return "held", ""
    return "held (point)", "interval crosses"


def _tex(x):
    import re
    x = str(x).replace("%", "\\%").replace("_", "\\_").replace("&", "\\&")
    x = x.replace(">=", "$\\ge$").replace("<=", "$\\le$")
    x = re.sub(r"(^|\s)>(\s)", r"\1$>$\2", x)
    x = re.sub(r"(^|\s)<(\s)", r"\1$<$\2", x)
    return re.sub(r"(\d) us\b", r"\1 $\\mu$s", x)


